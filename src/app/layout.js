import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { ClerkProvider } from "@clerk/nextjs";

const geistSans = Geist({
    variable: "--font-geist-sans",
    subsets: ["latin"],
});

const geistMono = Geist_Mono({
    variable: "--font-geist-mono",
    subsets: ["latin"],
});

export const metadata = {
    title: "Create Next App",
    description: "Generated by create next app",
};

// Runs before paint, synchronously, in <head> — this is what prevents a
// flash of the wrong theme on load. Reads localStorage first, falls back to
// system preference on first visit. Wrapped in try/catch since
// localStorage/matchMedia can throw in some privacy-mode/embedded contexts,
// and a broken theme script must never be the thing that breaks the page.
const themeInitScript = `
(function () {
  try {
    var stored = localStorage.getItem('theme');
    var theme = (stored === 'light' || stored === 'dark')
      ? stored
      : (window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light');
    document.documentElement.setAttribute('data-theme', theme);
  } catch (e) {}
})();
`;

export default function RootLayout({ children }) {
    return (
        <html lang="en">
        <head>
            <script dangerouslySetInnerHTML={{ __html: themeInitScript }} />
        </head>
        <body
            className={`${geistSans.variable} ${geistMono.variable} antialiased`}
        >
        {/* ✅ ClerkProvider MUST be inside <body> */}
        <ClerkProvider>
            {children}
        </ClerkProvider>
        </body>
        </html>
    );
}
